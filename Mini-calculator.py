first_num=int(input("Enter your first number:"))
second_num=int(input("Enter your second number:"))


add_result = first_num + second_num
print(f"{first_num} + {second_num} = {add_result}")

multiply_result = first_num * second_num
print(f"{first_num} * {second_num} = {multiply_result}")

subtract_result = first_num - second_num
print(f"{first_num} - {second_num} = {subtract_result}")

division_result = first_num / second_num
print(f"{first_num} / {second_num} = {division_result}")
